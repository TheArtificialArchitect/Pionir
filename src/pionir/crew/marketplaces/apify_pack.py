import hashlib
import io
import json
import zipfile

from pionir.adapters.marketplace_listing import claim_problems

from ..builds.package import STAMP
from . import images

VERSION = "0.1"
PACKAGE = "actor-source.zip"
ICON = "icon.png"
SDK = "apify>=2.3,<4"
HTTPX = "httpx>=0.27,<1"
DISCLOSURE = ("The core of this Actor was written by an AI coding system; its tests were run "
              "and the code was reviewed before release.")
LISTING_KEYS = frozenset({"slug", "actor_name", "title", "description", "seo_title",
                          "seo_description", "categories", "version", "pricing",
                          "package_name", "package_sha256", "files", "readme_md",
                          "icon_name", "icon_sha256"})

DOCKERFILE = """FROM apify/actor-python:3.12

USER myuser
COPY --chown=myuser:myuser requirements.txt ./
RUN pip install --no-cache-dir -r requirements.txt
COPY --chown=myuser:myuser . ./
RUN python3 -m compileall -q src/
CMD ["python3", "-m", "src"]
"""

MAIN_PY = '''"""The Apify Actor around {name}.

Generated by the packager from the product's spec (never model-written): it reads the input,
{how}, hands ONE record at a time to the core's process(), stores every result and charges
one "{event}" event for each result without an "error" key. A record that fails is stored
with its error and is not charged.
"""
from __future__ import annotations

import os
import sys

from apify import Actor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from {package} import process  # noqa: E402 - the core lives beside this file

EVENT = "{event}"
MAX_TEXT = 5_000_000
DEFAULT_MAX = 100


def _limit(actor_input: dict) -> int:
    value = actor_input.get("maxItems")
    return value if isinstance(value, int) and value > 0 else DEFAULT_MAX


def _urls(actor_input: dict) -> list:
    out = []
    for item in actor_input.get("startUrls") or []:
        url = item.get("url") if isinstance(item, dict) else item
        if isinstance(url, str) and url.startswith(("http://", "https://")):
            out.append(url)
    return out


async def _fetch(client, url: str) -> dict:
    try:
        response = await client.get(url, follow_redirects=True, timeout=30.0)
        return {{"url": str(response.url), "status": response.status_code,
                "content_type": response.headers.get("content-type", ""),
                "text": response.text[:MAX_TEXT]}}
    except Exception as exc:  # noqa: BLE001 - one bad URL must not stop the run
        Actor.log.warning(f"could not fetch {{url}}: {{type(exc).__name__}}")
        return {{"url": url, "status": 0, "content_type": "", "text": "",
                "fetch_error": f"{{type(exc).__name__}}: {{exc}}"[:300]}}


def _run_core(record: dict) -> dict:
    try:
        result = process(record)
    except Exception as exc:  # noqa: BLE001 - stored as an error, never charged
        return {{"error": f"{{type(exc).__name__}}: {{exc}}"[:300]}}
    if not isinstance(result, dict):
        return {{"error": "the core returned something that is not an object"}}
    return result


async def _emit(result: dict) -> bool:
    """Store one result; charge it when it has no error. False: stop the run."""
    await Actor.push_data(result)
    if "error" in result:
        return True
    charged = await Actor.charge(event_name=EVENT)
    if charged.event_charge_limit_reached:
        Actor.log.info("the run's spending limit is reached; stopping")
        return False
    return True


async def main() -> None:
    async with Actor:
        actor_input = await Actor.get_input() or {{}}
        limit = _limit(actor_input)
{body}
'''

BODY_FETCH = '''        import httpx

        urls = _urls(actor_input)[:limit]
        if not urls:
            await Actor.fail(status_message="no URLs in startUrls")
            return
        async with httpx.AsyncClient(headers={"User-Agent": "Mozilla/5.0 (Apify Actor)"}) \\
                as client:
            for url in urls:
                if not await _emit(_run_core(await _fetch(client, url))):
                    break
'''

BODY_ITEMS = '''        items = [x for x in (actor_input.get("items") or []) if isinstance(x, dict)][:limit]
        if not items:
            await Actor.fail(status_message="no JSON objects in items")
            return
        for item in items:
            if not await _emit(_run_core(item)):
                break
'''

MAIN_ENTRY = '''import asyncio

from .main import main

asyncio.run(main())
'''

