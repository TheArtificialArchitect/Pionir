"""An Apify Actor around an approved core build, and its Store listing - deterministic.

The night builds produce the CORE (a standard-library Python package with ``process(record)``,
reviewed by Claude, no network). This module writes everything around it from the spec, the
same way every time, so nothing here is model-written code:

- ``.actor/actor.json``, ``.actor/input_schema.json``, ``.actor/Dockerfile`` (the official
  ``apify/actor-python`` image), ``requirements.txt`` (the Apify SDK and httpx);
- ``src/main.py`` - the wrapper: reads the input, fetches each URL (``io=fetch_urls``) or takes
  each JSON item (``io=items``), calls ``process`` on ONE record at a time, stores every result
  and charges ONE pay-per-event event per result WITHOUT an ``error`` (a failed record is
  stored and not charged), and stops at the run's spending limit;
- ``README.md`` - the Store page, built from the spec's checked words (what it does, the
  features, input, output, the exact price, the honest limits, and how it was made);
- the core package itself (``src/<package>/``) and its licence files.

The listing (``listing.json``) is exactly the ``apify.publish`` payload.
"""
