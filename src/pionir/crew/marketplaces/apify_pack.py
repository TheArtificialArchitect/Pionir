def short_title(name: str) -> str:
    t = name.split(":", 1)[0].strip()
    return t if len(t) <= 60 else t[:57].rsplit(" ", 1)[0] + "..."


def _clip_words(text: str, n: int) -> str:
    text = " ".join(text.split())
    if len(text) <= n:
        return text
    return text[:n - 3].rsplit(" ", 1)[0].rstrip(",;:") + "..."


def input_schema(spec: dict) -> dict:
    title = short_title(spec["name"])
    limit = {"title": "Maximum results", "type": "integer", "default": 100, "minimum": 1,
             "maximum": 10000,
             "description": "Stop after this many results (each successful one is charged)."}
    if spec["listing"]["io"] == "fetch_urls":
        props = {"startUrls": {"title": "URLs", "type": "array", "editor": "requestListSources",
                               "description": "The pages to process: one result per page.",
                               "prefill": [{"url": "https://example.com"}]},
                 "maxItems": limit}
        required = ["startUrls"]
    else:
        props = {"items": {"title": "Items", "type": "array", "editor": "json",
                           "description": "The JSON objects to process: one result each.",
                           "prefill": [{}]},
                 "maxItems": limit}
        required = ["items"]
    return {"title": f"{title} input", "type": "object", "schemaVersion": 1,
            "properties": props, "required": required}


def readme(spec: dict) -> str:
    lst, ev = spec["listing"], spec["listing"]["event"]
    features = "\n".join(f"- {f}" for f in spec["features"])
    if lst["io"] == "fetch_urls":
        given = ("A list of URLs (`startUrls`). The Actor fetches each page once and processes "
                 "it; a page that cannot be fetched gives a result with an `error`.")
    else:
        given = "A JSON array of objects (`items`); each is processed on its own."
    per_k = float(ev["price_usd"]) * 1000
    return (f"# {short_title(spec['name'])}\n\n{spec['summary']}\n\n## What it does\n\n"
            f"{spec['brief']}\n\n## Features\n\n{features}\n\n## Input\n\n{given} "
            "`maxItems` caps the number of results.\n\n## Output\n\nOne dataset item per "
            "input. A record that could not be processed is stored with an `error` field.\n\n"
            f"## Pricing\n\nPay per event: **${float(ev['price_usd']):.4f} per successful result** "
            f"(\"{ev['title']}\": {ev['description']}) - ${per_k:.2f} per 1,000 results - plus "
            "Apify's standard Actor start event. Results with an `error` are not charged.\n\n"
            f"## Limits\n\n{spec['limits']}\n\n## How it was made\n\n{DISCLOSURE}\n")


def _zip(files: dict) -> bytes:
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as zf:
        for rel in sorted(files):
            info = zipfile.ZipInfo(rel, date_time=STAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            zf.writestr(info, files[rel], compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    return out.getvalue()


def source_files(spec: dict, core: dict) -> dict:
    """{path: bytes} of the whole Actor: the core's package and licence, and the wrapper."""
    pkg = spec["package"]
    lst = spec["listing"]
    out: dict = {}
    prefix = f"src/{pkg}/"
    for rel, data in core.items():
        if rel.startswith(prefix) and not rel.endswith((".pyc", ".pyo")):
            out[rel] = data
    if f"{prefix}__init__.py" not in out:
        raise ValueError(f"the build has no {prefix}__init__.py: there is no core to wrap")
    for rel in ("LICENSE.txt",):
        if rel in core:
            out[rel] = core[rel]
    if "README.md" in core:
        out["docs/CORE.md"] = core["README.md"]
    how = ("fetches each URL it is given" if lst["io"] == "fetch_urls"
           else "takes each JSON item it is given")
    out["src/main.py"] = MAIN_PY.format(
        name=short_title(spec["name"]), how=how, event=lst["event"]["name"], package=pkg,
        body=BODY_FETCH if lst["io"] == "fetch_urls" else BODY_ITEMS).encode()
    out["src/__main__.py"] = MAIN_ENTRY.encode()
    out["requirements.txt"] = (SDK + "\n" + (HTTPX + "\n" if lst["io"] == "fetch_urls"
                                             else "")).encode()
    out["THIRD_PARTY.txt"] = THIRD_PARTY.format(package=pkg).encode()
    out[".actor/Dockerfile"] = DOCKERFILE.encode()
    out[".actor/input_schema.json"] = (json.dumps(input_schema(spec), indent=2) + "\n").encode()
    out[".actor/actor.json"] = (json.dumps({
        "actorSpecification": 1, "name": spec["slug"], "title": short_title(spec["name"]),
        "description": spec["summary"], "version": VERSION, "buildTag": "latest",
        "input": "./input_schema.json", "dockerfile": "./Dockerfile"}, indent=2) + "\n").encode()
    out["README.md"] = readme(spec).encode()
    return out


def draft(spec: dict, core: dict) -> tuple:
    """``(listing, {file name: bytes}, problems)``: the listing.json, the files to write
    beside it (the source zip and the icon), and every reason it may not be submitted."""
    files = source_files(spec, core)
    package = _zip(files)
    icon = images.icon(spec["name"], 512)
    ev = spec["listing"]["event"]
    text = readme(spec)
    listing = {
        "slug": spec["slug"], "actor_name": spec["slug"], "title": short_title(spec["name"]),
        "description": _clip_words(spec["summary"], 300),
        "seo_title": short_title(spec["name"]),
        "seo_description": _clip_words(spec["summary"], 156),
        "categories": list(spec["listing"]["categories"]), "version": VERSION,
        "pricing": {"model": "PAY_PER_EVENT", "event_name": ev["name"],
                    "event_title": ev["title"], "event_description": ev["description"],
                    "price_usd": float(ev["price_usd"])},
        "package_name": PACKAGE, "package_sha256": hashlib.sha256(package).hexdigest(),
        "files": sorted(files), "readme_md": text, "icon_name": ICON,
        "icon_sha256": hashlib.sha256(icon).hexdigest()}
    problems = claim_problems({"title": listing["title"], "description": listing["description"],
                               "readme_md": text})
    return listing, {PACKAGE: package, ICON: icon}, problems
