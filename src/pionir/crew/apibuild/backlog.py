@dataclass
class Backlog:
    """What the file holds: the entries that passed, in build order, and each that did not."""

    entries: list = field(default_factory=list)
    invalid: list = field(default_factory=list)       # [(id-or-index, [reasons])]
    seeded: bool = False


def _text(value, limit: int, what: str, reasons: list, *, minimum: int = 1) -> str:
    if not isinstance(value, str) or not minimum <= len(value.strip()) <= limit:
        reasons.append(f"{what} must be text of {minimum} to {limit} characters")
        return ""
    if _CONTROL.search(value):
        reasons.append(f"{what} has control characters")
    if MODEL_WORDS.search(value):
        reasons.append(f"{what} names a model or an AI vendor, which never reaches a customer")
    return value


def check_entry(entry) -> list:
    """Why this entry cannot be built (empty: it can). Fail closed: anything not understood
    is a reason."""
    if not isinstance(entry, dict):
        return ["the entry is not an object"]
    reasons: list = []
    pid = entry.get("id")
    if not isinstance(pid, str) or not ID.fullmatch(pid):
        reasons.append("id must be 3 to 20 lowercase letters (it is the path under /v1/)")
        pid = None
    elif pid in RESERVED_IDS:
        reasons.append(f"id {pid!r} is already a product or a reserved word")
    _text(entry.get("name"), NAME_MAX, "name", reasons)
    _text(entry.get("summary"), SUMMARY_MAX, "summary", reasons, minimum=20)
    _text(entry.get("why"), WHY_MAX, "why", reasons, minimum=20)
    endpoints = entry.get("endpoints")
    if not isinstance(endpoints, list) or not 1 <= len(endpoints) <= MAX_ENDPOINTS:
        reasons.append(f"endpoints must be a list of 1 to {MAX_ENDPOINTS}")
        endpoints = []
    seen = set()
    for i, ep in enumerate(endpoints):
        where = f"endpoint {i + 1}"
        if not isinstance(ep, dict):
            reasons.append(f"{where} is not an object")
            continue
        method, path = ep.get("method"), ep.get("path")
        if method not in METHODS:
            reasons.append(f"{where}: method must be GET or POST")
        if not isinstance(path, str) or pid is None or not re.fullmatch(
                rf"/v1/{pid}(/[a-z0-9-]+)*", path):
            reasons.append(f"{where}: path must be /v1/{pid or '<id>'} then lowercase "
                           "segments")
        elif (method, path) in seen:
            reasons.append(f"{where}: {method} {path} is listed twice")
        else:
            seen.add((method, path))
        _text(ep.get("description"), TEXT_MAX, f"{where} description", reasons, minimum=10)
        _text(ep.get("example_request"), EXAMPLE_MAX, f"{where} example_request", reasons)
        _text(ep.get("example_response"), EXAMPLE_MAX, f"{where} example_response", reasons)
    limits = entry.get("limits")
    if not isinstance(limits, list) or not 1 <= len(limits) <= MAX_LIMITS:
        reasons.append(f"limits must be a list of 1 to {MAX_LIMITS} statements")
    else:
        for i, text in enumerate(limits):
            _text(text, 200, f"limit {i + 1}", reasons)
    for key, kind in (("validated", bool), ("priority", int), ("retry", int)):
        value = entry.get(key, kind())
        if not isinstance(value, kind) or (kind is int and isinstance(value, bool)):
            reasons.append(f"{key} must be "
                           f"{'true or false' if kind is bool else 'a whole number'}")
    if entry.get("state", "queued") not in ("queued", "removed"):
        reasons.append("state must be queued or removed")
    return reasons


def parse_backlog(doc) -> Backlog:
    """Entries in build order: valid and queued only, by priority (high first), file order for
    ties. An invalid entry is reported, never built; ``removed`` is skipped quietly."""
    out = Backlog()
    raw = doc.get("entries") if isinstance(doc, dict) else None
    if not isinstance(raw, list):
        out.invalid.append(("backlog", ["the file has no entries list"]))
        return out
    seen: set = set()
    good: list = []
    for i, entry in enumerate(raw[:MAX_ENTRIES]):
        label = entry.get("id") if isinstance(entry, dict) and isinstance(entry.get("id"), str) \
            else f"#{i + 1}"
        if isinstance(entry, dict) and entry.get("state") == "removed":
            continue
        reasons = check_entry(entry)
        if not reasons and entry["id"] in seen:
            reasons = [f"id {entry['id']!r} appears twice"]
        if reasons:
            out.invalid.append((_clip(label, 30), [_clip(r, 160) for r in reasons[:6]]))
            continue
        seen.add(entry["id"])
        good.append((i, entry))
    if len(raw) > MAX_ENTRIES:
        out.invalid.append(("backlog", [f"only the first {MAX_ENTRIES} entries are read"]))
    good.sort(key=lambda p: (-int(p[1].get("priority", 0)), p[0]))
    out.entries = [e for _i, e in good]
    return out


def load_backlog(directory, *, write_seed: bool = True) -> Backlog:
    """Read ``<directory>/backlog.json``. Missing: the seed is written (once) and returned.
    Unreadable or not JSON: ``ValueError`` - never overwritten, never guessed."""
    path = Path(directory) / BACKLOG_FILE
    if not path.exists():
        seed = {"version": 1, "entries": _seed(),
                "note": "Seed ideas are UNVALIDATED guesses. Edit freely: add, remove "
                        "(state: removed), reorder (priority), or set validated: true when "
                        "traffic says an idea is wanted."}
        if write_seed:
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_suffix(".tmp")
            tmp.write_text(json.dumps(seed, indent=1), encoding="utf-8")
            atomic.replace(tmp, path)
            log.info("api_builder: wrote the seed backlog to %s", path)
        out = parse_backlog(seed)
        out.seeded = True
        return out
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ValueError(f"{path} cannot be read ({exc})") from exc
    return parse_backlog(doc)
