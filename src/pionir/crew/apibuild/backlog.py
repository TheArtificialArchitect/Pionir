"""The API builder's backlog: each product on paper, owner-editable, checked, fail closed.

``<apibuilds_dir>/backlog.json`` is ``{"version": 1, "entries": [...]}``. The owner edits it by
hand (add, remove, reorder, ``"retry": n`` to reopen a shelved product); the worker only ever
READS it after the first run, which writes the seed. An entry is the whole product on paper:

``id`` (lowercase letters: it is the path segment under /v1/), ``name``, ``summary``,
``endpoints`` (method, path, description, an example request and response), ``limits`` (what
the docs will state), and ``why`` (who searches for it). Optional: ``validated`` (default
false - the seeds are guesses until the traffic says otherwise), ``priority`` (higher builds
first; ties keep file order), ``state`` (``queued`` or ``removed``), ``retry`` (an integer;
raising it reopens a shelved product).

Every customer-facing word is the entry's own, so it is checked here: no model words, no
control characters, bounded. An entry that fails is reported with its reasons and never built.
"""
from __future__ import annotations

