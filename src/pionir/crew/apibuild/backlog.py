METHODS = ("GET", "POST")
MAX_ENTRIES = 50
MAX_ENDPOINTS = 6
MAX_LIMITS = 8
NAME_MAX, SUMMARY_MAX, TEXT_MAX, EXAMPLE_MAX, WHY_MAX = 60, 240, 400, 600, 400
# words that must never reach a customer, in the backlog's copy or in the built file
